#!/usr/bin/env node
// Builds dist/ from src/tokens.mjs and src/base.css:
//   tokens.css  the --sdu-* custom properties for light and dark, at zero specificity (:where), so any
//               rule of yours wins regardless of load order
//   base.css    the .sdu-* classes
//   styles.css  tokens.css + base.css (what Angular and React pages load)
//   host.css    defaults for Shadow DOM (used by @smartdevutils/elements)
//   index.js / index.cjs / index.d.ts   the same CSS as strings, plus the token values
// `--check` builds in memory and fails on a var(--sdu-c-*) that is not a token.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { COMMON, LIGHT, DARK, TOKEN_NAMES } = await import(pathToFileURL(join(root, 'src/tokens.mjs')).href)

const decls = (obj, prefix, indent = '  ') =>
  Object.entries(obj)
    .map(([k, v]) => `${indent}--${prefix}${k}: ${v};`)
    .join('\n')

export function buildCss() {
  const tokens = [
    '/* @smartdevutils/theme tokens. Override any --sdu-* property on :root, a container or one component. */',
    ':where(:root), :where([data-theme="light"]) {',
    decls({ ...COMMON, ...LIGHT }, 'sdu-'),
    '}',
    '@media (prefers-color-scheme: dark) {',
    '  :where(:root:not([data-theme="light"])) {',
    decls(DARK, 'sdu-', '    '),
    '  }',
    '}',
    ':where([data-theme="dark"]) {',
    decls(DARK, 'sdu-'),
    '}',
    '',
  ].join('\n')

  const host = [
    '/* Shadow DOM defaults. Page-level --sdu-* properties still win, because base.css reads them first. */',
    ':host {',
    '  display: block;',
    decls({ ...COMMON, ...LIGHT }, 'sdu-d-'),
    '}',
    ':host([hidden]) { display: none; }',
    '@media (prefers-color-scheme: dark) {',
    '  :host(:not([data-theme="light"])) {',
    decls(DARK, 'sdu-d-', '    '),
    '  }',
    '}',
    // data-sdu-scheme is set by the elements from the nearest ancestor's data-theme.
    ':host([data-sdu-scheme="light"]), :host([data-theme="light"]) {',
    decls(LIGHT, 'sdu-d-'),
    '}',
    ':host([data-sdu-scheme="dark"]), :host([data-theme="dark"]) {',
    decls(DARK, 'sdu-d-'),
    '}',
    '',
  ].join('\n')

  const all = { ...COMMON, ...LIGHT }
  const resolved = [
    '/* @smartdevutils/theme base classes. */',
    '.sdu-root {',
    TOKEN_NAMES.map((k) => `  --sdu-c-${k}: var(--sdu-${k}, var(--sdu-d-${k}, ${all[k]}));`).join('\n'),
    '}',
  ].join('\n')
  const base = resolved + '\n' + readFileSync(join(root, 'src/base.css'), 'utf8')
  return { tokens, host, base, styles: tokens + '\n' + base }
}

function check(css) {
  const used = new Set([...css.base.matchAll(/var\(--sdu-c-([a-z-]+)\)/g)].map((m) => m[1]))
  const unknown = [...used].filter((n) => !TOKEN_NAMES.includes(n))
  if (unknown.length) throw new Error(`base.css uses unknown tokens: ${unknown.join(', ')}`)
  for (const k of Object.keys(LIGHT)) if (!(k in DARK)) throw new Error(`token ${k} has no dark value`)
  for (const k of Object.keys(DARK)) if (!(k in LIGHT)) throw new Error(`token ${k} has no light value`)
}

/** A small CSS minifier for the JS strings: drops comments and extra whitespace. The .css files stay readable. */
export function minify(text) {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    // Not around ':' in general: ".a :focus-visible" (descendant) differs from ".a:focus-visible".
    .replace(/\s*([{};,>])\s*/g, '$1')
    .replace(/:\s+/g, ':')
    .replace(/;}/g, '}')
    .trim()
}

function write(css) {
  const dist = join(root, 'dist')
  mkdirSync(dist, { recursive: true })
  writeFileSync(join(dist, 'tokens.css'), css.tokens)
  writeFileSync(join(dist, 'host.css'), css.host)
  writeFileSync(join(dist, 'base.css'), css.base)
  writeFileSync(join(dist, 'styles.css'), css.styles)

  const values = { common: COMMON, light: LIGHT, dark: DARK }
  const body = (exp) =>
    [
      `${exp('tokensCss')} = ${JSON.stringify(minify(css.tokens))};`,
      `${exp('baseCss')} = ${JSON.stringify(minify(css.base))};`,
      `${exp('stylesCss')} = ${JSON.stringify(minify(css.styles))};`,
      `${exp('hostCss')} = ${JSON.stringify(minify(css.host))};`,
      `${exp('TOKENS')} = ${JSON.stringify(values, null, 2)};`,
      `${exp('TOKEN_NAMES')} = ${JSON.stringify(TOKEN_NAMES)};`,
    ].join('\n') + '\n'
  writeFileSync(join(dist, 'index.js'), '// Generated by scripts/build.mjs.\n' + body((n) => `export const ${n}`))
  writeFileSync(
    join(dist, 'index.cjs'),
    '"use strict";\n// Generated by scripts/build.mjs.\nObject.defineProperty(exports, "__esModule", { value: true });\n' +
      body((n) => `exports.${n}`),
  )
  writeFileSync(
    join(dist, 'index.d.ts'),
    [
      '/** The --sdu-* custom properties for light and dark (tokens.css, minified). */',
      'export declare const tokensCss: string;',
      '/** The .sdu-* classes (base.css). */',
      'export declare const baseCss: string;',
      '/** tokens.css followed by base.css (styles.css). */',
      'export declare const stylesCss: string;',
      '/** Defaults for a Shadow DOM :host (host.css). */',
      'export declare const hostCss: string;',
      'export declare const TOKENS: {',
      '  common: Readonly<Record<string, string>>;',
      '  light: Readonly<Record<string, string>>;',
      '  dark: Readonly<Record<string, string>>;',
      '};',
      'export declare const TOKEN_NAMES: readonly string[];',
      '',
    ].join('\n'),
  )
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const css = buildCss()
  check(css)
  if (process.argv.includes('--check')) {
    console.log('theme check ok')
  } else {
    write(css)
    console.log('theme built: dist/{tokens,base,styles,host}.css and index.{js,cjs,d.ts}')
  }
}
