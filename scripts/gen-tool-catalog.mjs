#!/usr/bin/env node
// Generates packages/core/src/tools/catalog.ts from the website's tool registry.
//
//   node scripts/gen-tool-catalog.mjs <path to SmartDevUtils.Client/src/app>
//
// It keeps only what a runner, a generic UI or a recipe needs (id, slug, name, category,
// tool type, short description and modes) and drops the SEO text, FAQs and examples.
// The website registry stays the source of truth until the owner decides otherwise.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const appDir = process.argv[2]
if (!appDir) {
  console.error('usage: node scripts/gen-tool-catalog.mjs <path to SmartDevUtils.Client/src/app>')
  process.exit(1)
}

const require = createRequire(join(root, 'packages/core/package.json'))
const ts = require('typescript')

const src = readFileSync(join(appDir, 'data/tools-registry.ts'), 'utf8').replace(/^﻿/, '')
const js = ts.transpileModule(src, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText
const mod = { exports: {} }
new Function('module', 'exports', 'require', js)(mod, mod.exports, () => ({}))
const registry = mod.exports.TOOLS_REGISTRY
if (!Array.isArray(registry)) throw new Error('TOOLS_REGISTRY not found')

const catalog = registry.map((t) => ({
  id: t.id,
  slug: t.slug,
  name: t.name,
  category: t.category,
  toolType: t.toolType,
  description: t.description,
  modes: (t.modes ?? []).map((m) => ({
    id: m.id,
    label: m.label,
    ...(m.inputLabel ? { inputLabel: m.inputLabel } : {}),
    ...(m.outputLabel ? { outputLabel: m.outputLabel } : {}),
  })),
}))

const out = `// GENERATED by scripts/gen-tool-catalog.mjs from the website's data/tools-registry.ts. Do not edit by hand.
// ${catalog.length} tools. Regenerate after the website registry changes.
import type { ToolCatalogEntry } from './types'

export const TOOL_CATALOG: readonly ToolCatalogEntry[] = ${JSON.stringify(catalog)}
`
const target = join(root, 'packages/core/src/tools/catalog.ts')
writeFileSync(target, out)
console.log(`wrote ${catalog.length} tools to ${target}`)
